"""OFFLINE rule extractor: read each rulebook once, write data/events.yml (C1, structured output).

    uv run python extract_rules.py

For every event:
  1. send the cleaned rulebook text to the model, asking for an EventRules object (Pydantic);
  2. CHECK the result against the rulebook text: every evidence quote must appear in the text,
     and every number and date must be findable there. Anything that is not is flagged;
  3. fill facts the rulebook does not state from data/mock_fill.yml, and mark them as mock;
  4. compare with the hand-written baseline (data/events.hand.yml) and print the differences.
The tools later read events.yml, never the model's memory.
"""
import re
from datetime import date

import yaml

from config import settings
from models import build_model, load_prompt
from schemas import EventRules

MONTHS = ["", "january", "february", "march", "april", "may", "june", "july", "august",
          "september", "october", "november", "december"]
FIELDS = ["team_min", "team_max", "fee_bdt", "fee_per", "event_date", "reg_deadline",
          "all_departments", "eligible_level", "one_team_only"]


def norm(text: str) -> str:
    """Lowercase, no punctuation, single spaces: so a quote still matches after bullets and line breaks."""
    return re.sub(r"\s+", " ", re.sub(r"[^a-z0-9 ]", " ", text.lower())).strip()


def check(rules: EventRules, text: str) -> list[str]:
    """Problems found when comparing the extraction with the rulebook text. Empty = all verified."""
    body, problems = norm(text), []
    for quote in rules.evidence:
        if norm(quote) not in body:
            problems.append(f"quote not found in rulebook: '{quote[:60]}'")
    for name in ("team_min", "team_max", "fee_bdt"):
        value = getattr(rules, name)
        if value is not None and value > 1 and str(value) not in body.split():
            problems.append(f"{name}={value}: number not in the rulebook text")
    for name in ("event_date", "reg_deadline"):
        d: date | None = getattr(rules, name)
        if d and not (str(d.day) in body.split() and MONTHS[d.month] in body):
            problems.append(f"{name}={d}: day or month not in the rulebook text")
    for dept in rules.departments:
        if dept.lower() not in body and "fse" not in body:
            problems.append(f"department {dept} not in the rulebook text")
    return problems


def to_record(rules: EventRules) -> dict:
    """EventRules -> the record shape in events.yml (what the tools read)."""
    return dict(
        team_min=rules.team_min, team_max=rules.team_max, fee_bdt=rules.fee_bdt, fee_per=rules.fee_per,
        event_date=rules.event_date, reg_deadline=rules.reg_deadline,
        eligible_departments="all" if rules.all_departments else (rules.departments or None),
        eligible_level=rules.eligible_level, one_team_only=rules.one_team_only)


def main() -> None:
    base = yaml.safe_load((settings.DATA_DIR / "events.hand.yml").read_text(encoding="utf-8"))["events"]
    mock = yaml.safe_load((settings.DATA_DIR / "mock_fill.yml").read_text(encoding="utf-8"))
    model = build_model(schema=EventRules)
    template, version = load_prompt("extract_prompt")
    out, total_flags = {}, 0

    for event, meta in base.items():
        text = (settings.RULEBOOK_DIR / "clean" / f"{event}.md").read_text(encoding="utf-8")
        rules: EventRules = model.invoke(template.format(event=meta["name"], text=text),
                                         config={"run_name": f"extract:{event}", "tags": [f"prompt:extract_prompt:{version}"]})
        rec, flags = to_record(rules), check(rules, text)

        mock_fields = []
        for key, value in mock.get(event, {}).items():       # fill what the rulebook leaves null
            target = "eligible_departments" if key == "all_departments" else key
            if rec.get(target) is None:
                rec[target] = "all" if key == "all_departments" and value else value
                mock_fields.append(target)

        out[event] = {"name": meta["name"], "rulebook": meta["rulebook"], **rec, "source": "rulebook",
                      "mock_fields": mock_fields, "extraction_flags": flags}

        diffs = [f"{k}: hand={base[event].get(k)!r} extracted={rec[k]!r}" for k in rec
                 if k not in mock_fields and base[event].get(k) != rec[k]]
        status = "verified" if not flags else f"{len(flags)} FLAG(S)"
        print(f"{event:17} {status}" + (f"  mock-filled: {mock_fields}" if mock_fields else ""))
        for f in flags:
            print(f"    flag: {f}")
        for d in diffs:
            print(f"    differs from hand-written baseline -> {d}")
        total_flags += len(flags)

    header = ("# GENERATED by extract_rules.py from the cleaned rulebooks. Do not edit by hand:\n"
              "# edit the rulebook text or data/mock_fill.yml and run the extractor again.\n"
              "# mock_fields lists values invented because the rulebook does not state them.\n")
    (settings.DATA_DIR / "events.yml").write_text(header + yaml.safe_dump({"events": out}, sort_keys=False), encoding="utf-8")
    print(f"\nwrote data/events.yml ({len(out)} events, {total_flags} flags)")


if __name__ == "__main__":
    main()
